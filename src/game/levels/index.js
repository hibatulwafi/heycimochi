/**
 * The five levels, hardest last.
 *
 * Designing a level is editing text. Every row must be the same length; the
 * parser throws on a ragged map rather than building a world with holes in it.
 *
 *   #  solid ground      =  floating platform (one-way: landable from above)
 *   ^  spikes (hazard)   f  fish (+10)
 *   c  coin (+5)         P  player spawn
 *   G  goal basket       .  empty
 *
 * Every grid is 10 rows, which is what sets VIEW_HEIGHT in config.js — the
 * whole world height is always on screen and the camera only scrolls sideways.
 * Row 8 is the walkable surface, row 9 the fill beneath it.
 *
 * Reachability at GRAVITY 1050 / JUMP 350 / WALK 110 / RUN 155:
 *   a walking jump travels ~73px, clearing gaps of up to 3 tiles
 *   a running jump travels ~103px, clearing gaps of up to 5 tiles
 * So no gap here is wider than 5 tiles. The difficulty curve is gap width and
 * gap frequency, not gap impossibility: Backyard Run is all 3s and 4s with
 * long safe runs between them, while Mochi's Marathon is twelve gaps — mostly
 * 5s — with 3-tile islands to land on and barely any flat ground to rest.
 *
 * Platforms sit only over solid ground. A platform spanning a pit would turn
 * the hardest jumps into a free ride.
 */
